// Seriler 9000'den 1000'e iner; her serinin içindeki kodlar artarak kalır.
export function ralClassicSerileri() {
    const gruplar = new Map();
    for (const renk of RAL_CLASSIC_KARTELA) {
        const seri = `${renk.kod.slice(4, 5)}000`;
        if (!gruplar.has(seri)) {
            gruplar.set(seri, { seri, etiket: RAL_CLASSIC_SERI_ETIKETLERI[seri], renkler: [] });
        }
        gruplar.get(seri).renkler.push(renk);
    }
    return [...gruplar.values()].sort((a, b) => Number(b.seri) - Number(a.seri));
}
